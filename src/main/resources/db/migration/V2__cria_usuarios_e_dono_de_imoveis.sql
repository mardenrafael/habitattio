CREATE TABLE usuarios (
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    nome       varchar(100) NOT NULL,
    email      varchar(254) NOT NULL,
    senha_hash varchar(60)  NOT NULL,
    CONSTRAINT pk_usuarios PRIMARY KEY (id),
    CONSTRAINT ck_usuarios_nome_nao_vazio CHECK (nome !~ '^\s*$'),
    CONSTRAINT ck_usuarios_email_normalizado CHECK (email = lower(btrim(email)) AND email <> ''),
    CONSTRAINT uq_usuarios_email UNIQUE (email),
    CONSTRAINT ck_usuarios_senha_hash_bcrypt CHECK (senha_hash ~ '^\$2[aby]\$\d{2}\$[./A-Za-z0-9]{53}$')
);

ALTER TABLE imoveis
    ADD COLUMN usuario_id    bigint      NOT NULL,
    ADD COLUMN identificador varchar(50) NOT NULL,
    ADD CONSTRAINT fk_imoveis_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE RESTRICT,
    ADD CONSTRAINT ck_imoveis_identificador_nao_vazio CHECK (identificador !~ '^\s*$'),
    ADD CONSTRAINT ck_imoveis_identificador_sem_espacos_nas_pontas CHECK (identificador = btrim(identificador));

CREATE UNIQUE INDEX uq_imoveis_usuario_identificador ON imoveis (usuario_id, lower(identificador));
